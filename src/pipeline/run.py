"""Week 2 preprocessing pipeline: raw files -> cleaned, feature-engineered daily dataset.

Runs fully offline on the committed raw files (no API keys), so it can be scheduled
on GitHub Actions.

Usage:  python -m src.pipeline.run            # build, validate, write outputs
        python -m src.pipeline.run --check    # build and validate only (CI)
"""

from __future__ import annotations

import argparse
import hashlib
import json
from datetime import datetime, timezone

import numpy as np
import pandas as pd

from ..data_sources.config import END_DATE, PAPER_ANCHOR_DATE, RAW_DIR, ROOT, START_DATE
from .clean import check_prices, gap_report, load_raw, outlier_screen
from .features import FEATURES, build_features

OUT_DIR = ROOT / "data" / "processed"
DOC_DIR = ROOT / "deliverables" / "week2"
PARQUET = OUT_DIR / "features_daily.parquet"
CSV = OUT_DIR / "features_daily.csv"

# Plausible ranges for each feature (data check, not a model assumption)
RANGES = {
    "ret_1d": (-0.5, 0.5), "rv_21": (0.01, 2.5), "rv_63": (0.01, 2.0), "rv_252": (0.01, 1.5),
    "park_21": (0.01, 2.5), "volume_ratio_21": (0.05, 10), "div_ttm": (0.5, 10), "div_yield": (0.005, 0.08),
    "div_growth_yoy": (-0.5, 1.0), "vix": (0.05, 1.0), "corr_jpm_vix_63": (-1, 1), "r_3m": (-0.01, 0.1),
    "r_6m": (-0.01, 0.1), "r_1y": (-0.01, 0.1), "slope_10y_3m": (-0.05, 0.05), "rate_mom_21": (-0.03, 0.03),
    "rate_mom_63": (-0.05, 0.05), "fed_funds": (0, 0.1), "cpi_yoy": (-0.05, 0.15), "unrate": (0.02, 0.2),
    "sent_news": (0, 1), "sent_consumer": (0, 1),
}


def validate(df: pd.DataFrame, week1_calendar: pd.DatetimeIndex, div_span_max: float) -> dict:
    checks = []

    def add(name, ok, detail):
        checks.append({"check": name, "passed": bool(ok), "detail": detail})

    feats = list(FEATURES)
    add("At least 10 features", len(feats) >= 10, f"{len(feats)} features")
    add("One row per NYSE trading day, same calendar as Week 1", df.index.equals(week1_calendar), f"{len(df)} rows")
    blanks = int(df.isna().sum().sum())
    add("No blank values in any feature on any day", blanks == 0, f"{blanks} blanks")
    bad = {c: int((~df[c].between(*RANGES[c])).sum()) for c in feats if (~df[c].between(*RANGES[c])).any()}
    add("Every feature inside its plausible range", not bad, "all in range" if not bad else str(bad))
    add("Trailing dividend uses 4 payments spanning < 13 months", div_span_max < 400, f"max span {div_span_max:.0f} days")
    t = pd.Timestamp(PAPER_ANCHOR_DATE)
    a = df.loc[t]
    add("Week 1 anchor: S0 = $156.70 on 2021-08-23", abs(a.close - 156.70) < 0.005, f"{a.close:.2f}")
    add("Week 1 anchor: 1-year volatility = 27.2%", abs(a.rv_252 - 0.2722) < 0.0005, f"{a.rv_252:.4f}")
    add("Week 1 anchor: dividend yield = 2.30%", abs(a.div_yield - 0.0230) < 0.0001, f"{a.div_yield:.4f}")
    fred = pd.read_csv(RAW_DIR / "fred_daily.csv", index_col="date", parse_dates=True)["DGS1"].dropna()
    prev = fred.loc[: t - pd.Timedelta(days=1)]
    add("Anchor: r on 2021-08-23 equals raw DGS1 of the previous trading day",
        abs(a.r_1y - prev.iloc[-1] / 100) < 1e-12,
        f"{a.r_1y:.4f} = DGS1 on {prev.index[-1].date()} (same-day value used in Week 1: {fred.loc[t] / 100:.4f})")
    near_dup = [(x, y) for i, x in enumerate(feats) for y in feats[i + 1:] if abs(df[x].corr(df[y])) > 0.999]
    add("No two features are duplicates (|corr| <= 0.999)", not near_dup, str(near_dup) if near_dup else "none")
    return {"checks": checks, "passed": sum(c["passed"] for c in checks), "total": len(checks)}


def frame_hash(df: pd.DataFrame) -> str:
    """Fingerprint of one build. Platform-specific: macOS and Linux math libraries differ in
    the last bits of log/sqrt (about 1e-14), so cross-platform equality is checked with a
    tolerance in tests/test_pipeline.py instead."""
    return hashlib.sha256(pd.util.hash_pandas_object(df.round(12), index=True).values.tobytes()).hexdigest()[:16]


def numbers_tex(stats: dict) -> str:
    """LaTeX macros so the reports quote the pipeline's numbers instead of hand-typed ones."""
    def fmt(v):
        return f"{v:,}" if isinstance(v, int) else str(v)
    lines = ["% Auto-generated by src/pipeline/run.py. Do not edit by hand."]
    for k, v in stats.items():
        name = "".join(ch for ch in k.title() if ch.isalpha())
        lines.append(f"\\newcommand{{\\w{name}}}{{{fmt(v)}}}")
    return "\n".join(lines) + "\n"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="validate only, write nothing")
    args = ap.parse_args()

    raw = load_raw()
    week1_cal = pd.read_csv(RAW_DIR / "yahoo_jpm_daily.csv", index_col="date", parse_dates=True).index
    full_cal = raw.jpm.index

    price_checks = check_prices(raw)
    gaps = gap_report(raw, full_cal)
    flags, outliers = outlier_screen(raw.jpm.close, raw.vix.close)
    df = build_features(raw)
    res = validate(df, week1_cal, df.attrs["div_span_days_max"])

    print(f"== Week 2 pipeline: {len(df)} days x {len(FEATURES)} features ==")
    for c in res["checks"]:
        print(f"  [{'PASS' if c['passed'] else 'FAIL'}] {c['check']}: {c['detail']}")
    print(f"  {res['passed']}/{res['total']} checks passed")
    if res["passed"] != res["total"]:
        raise SystemExit(1)
    if args.check:
        print(f"  dataset hash {frame_hash(df)}")
        return

    OUT_DIR.mkdir(parents=True, exist_ok=True)
    DOC_DIR.mkdir(parents=True, exist_ok=True)
    df.to_parquet(PARQUET)
    df.to_csv(CSV, float_format="%.10g")
    flags.to_csv(OUT_DIR / "outlier_flags.csv")

    feat_doc = {k: {"group": g, "definition": d, "source": s, "unit": u} for k, (g, d, s, u) in FEATURES.items()}
    (OUT_DIR / "feature_dictionary.json").write_text(json.dumps(feat_doc, indent=2))
    log = {"built_at_utc": datetime.now(timezone.utc).isoformat(timespec="seconds"),
           "window": [START_DATE, END_DATE], "rows": len(df), "features": len(FEATURES),
           "dataset_hash": frame_hash(df), "price_checks": price_checks, "fred_gap_days": gaps,
           "gdelt_missing_days": [str(d.date()) for d in pd.date_range("2017-01-01", END_DATE).difference(raw.gdelt.index)],
           "outliers": outliers, "validation": res}
    (OUT_DIR / "cleaning_log.json").write_text(json.dumps(log, indent=2))

    t = pd.Timestamp(PAPER_ANCHOR_DATE)
    gap_total = sum(v["gap_days"] for v in gaps.values() if v["gap_days"])
    stats = {
        "rows": len(df), "features": len(FEATURES), "checks": res["total"],
        "gapdaysdgsone": gaps["DGS1"]["gap_days"], "gapdaysdff": gaps["DFF"]["gap_days"],
        "gapmaxdiffpp": max(v["max_abs_diff_ffill_vs_linear_pp"] for v in gaps.values()),
        "gaptotal": gap_total,
        "iqrlower": f"{outliers['k1.5']['lower']:.4f}", "iqrupper": f"{outliers['k1.5']['upper']:.4f}",
        "flagsonefive": outliers["k1.5"]["flagged_days"], "flagsthree": outliers["k3.0"]["flagged_days"],
        "flagsthreecovid": outliers["k3_flags_in_covid_window"],
        "flagsthreeoppvix": outliers["k3_flags_with_opposite_vix_move"],
        "reversals": len(outliers["spike_reversal_days"]),
        "gdeltmissing": len(log["gdelt_missing_days"]),
        "anchorrv": f"{df.loc[t, 'rv_252']*100:.1f}", "anchorq": f"{df.loc[t, 'div_yield']*100:.2f}",
        "anchorr": f"{df.loc[t, 'r_1y']*100:.2f}",
        "sentnewsmean": f"{df.sent_news.mean():.2f}", "sentconsmean": f"{df.sent_consumer.mean():.2f}",
        "datasethash": frame_hash(df),
    }
    (DOC_DIR / "week2_numbers.tex").write_text(numbers_tex(stats))
    (DOC_DIR / "week2_stats.json").write_text(json.dumps(stats, indent=2))
    print(f"Wrote {PARQUET.relative_to(ROOT)}, {CSV.relative_to(ROOT)} and logs; hash {frame_hash(df)}")


if __name__ == "__main__":
    main()
